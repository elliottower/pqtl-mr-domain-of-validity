"""Fast analysis model for the V8 power simulation (pure logic; no Modal dependency).

Data are generated by power_v9_logic.simulate (crossed gene intercept, gene random slope on S,
indication intercept, multiple-membership drug intercept). Each simulated dataset is analysed
by a logistic regression whose standard errors are two-way cluster-robust (Cameron, Gelbach &
Miller): clusters are (1) connected components of the gene-drug-program graph, so genes linked
by a shared multi-target drug form one cluster, and (2) indications. Clustering at the
component level covers the gene random slope and drug sharing and is conservative relative to
gene clustering. The decision rule is a one-sided z >= 1.645 on the focal coefficient, the
flat-prior analogue of the registered Pr(beta > 0) >= 0.95. This is a stand-in for the
registered Bayesian model; power_v9_calibrate.py compares the two on selected scenarios.
"""
from math import erf, log, sqrt

import numpy as np
import pandas as pd
import scipy.sparse as sp
from scipy.sparse.csgraph import connected_components

from power_v9_logic import LOG_SESOI, Scenario, Structure, simulate

Z_ONE_SIDED = 1.6448536269514722


def component_clusters(path) -> np.ndarray:
    """Connected components of the bipartite gene / drug-program graph, per hypothesis."""
    df = pd.read_csv(path)
    genes = {g: i for i, g in enumerate(sorted(df["gene_id"].unique()))}
    progs = sorted({p for s in df["drug_program_ids"].fillna("") for p in str(s).split(";") if p})
    pidx = {p: len(genes) + j for j, p in enumerate(progs)}
    rows, cols = [], []
    for g, s in zip(df["gene_id"], df["drug_program_ids"].fillna("")):
        for p in str(s).split(";"):
            if p:
                rows.append(genes[g])
                cols.append(pidx[p])
    n = len(genes) + len(progs)
    adj = sp.csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(n, n))
    _, labels = connected_components(adj, directed=False)
    return np.array([labels[genes[g]] for g in df["gene_id"]])


def _fit_logit(x, y, iters=50):
    beta = np.zeros(x.shape[1])
    for _ in range(iters):
        p = 1 / (1 + np.exp(-(x @ beta)))
        w = p * (1 - p)
        h = x.T @ (x * w[:, None])
        step = np.linalg.solve(h, x.T @ (y - p))
        beta += step
        if np.max(np.abs(step)) < 1e-8:
            break
    p = 1 / (1 + np.exp(-(x @ beta)))
    return beta, p


def _meat(scores, groups):
    _, inv = np.unique(groups, return_inverse=True)
    summed = np.zeros((inv.max() + 1, scores.shape[1]))
    np.add.at(summed, inv, scores)
    return summed.T @ summed


def fit_two_way(x, y, g1, g2):
    beta, p = _fit_logit(x, y)
    bread = np.linalg.inv(x.T @ (x * (p * (1 - p))[:, None]))
    s = x * (y - p)[:, None]
    g12 = g1.astype(np.int64) * (g2.max() + 1) + g2
    v = bread @ (_meat(s, g1) + _meat(s, g2) - _meat(s, g12)) @ bread
    evals, evecs = np.linalg.eigh(v)
    v = evecs @ np.diag(np.clip(evals, 0, None)) @ evecs.T
    return beta, np.sqrt(np.diag(v))


def _cdf(z):
    return 0.5 * (1 + erf(z / sqrt(2)))


def run_rep_fast(rng, st: Structure, comp: np.ndarray, sc: Scenario, mode: str) -> dict:
    y, s = simulate(rng, st, sc, mode)
    base = {"n_supportive": int(s.sum()),
            "n_supportive_genes_aligned": int(len(np.unique(st.gene[(s == 1) & (st.aligned == 1)]))),
            "n_supportive_genes_blocking": int(len(np.unique(st.gene[(s == 1) & (st.aligned == 0)])))}
    if s.sum() == 0 or y.min() == y.max():
        return {**base, "failed": True, "reject": False, "reject_sesoi": False}
    one = np.ones_like(s)
    if mode == "h1":
        x = np.column_stack([one, s, st.aligned, s * st.aligned])
    elif mode == "h4":
        x = np.column_stack([one, s, st.cns, s * st.cns])
    else:
        x = np.column_stack([one, s])
    try:
        beta, se = fit_two_way(x, y, comp, st.indication)
    except np.linalg.LinAlgError:
        return {**base, "failed": True, "reject": False, "reject_sesoi": False}
    b, e = float(beta[-1]), float(se[-1])
    if not np.isfinite(b) or not np.isfinite(e) or e <= 0 or abs(b) > 15:
        return {**base, "failed": True, "reject": False, "reject_sesoi": False}
    sign = -1.0 if mode == "h4" else 1.0
    z = sign * b / e
    return {**base, "failed": False, "estimate": b, "se": e,
            "reject": z >= Z_ONE_SIDED,
            "reject_sesoi": (sign * b - LOG_SESOI) / e >= Z_ONE_SIDED,
            "pr_gt0_flat": _cdf(z)}
